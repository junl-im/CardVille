'use strict';
const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const html=fs.readFileSync('web/index.html','utf8');
const shell=fs.readFileSync('web/js/lany-shell.js','utf8');
const css=fs.readFileSync('web/css/lany-hard-v40.css','utf8');
const normalSource=html.match(/const LEVELS = \[([\s\S]*?)\];/);
const hardSource=html.match(/const HARD_LEVELS=LEVELS\.map\([\s\S]*?\n\}\);/);
assert(normalSource&&hardSource,'Both campaigns must be defined');
const normal=vm.runInNewContext('['+normalSource[1]+']');
const hard=vm.runInNewContext(hardSource[0]+'\nHARD_LEVELS',{LEVELS:normal,Math});
assert.equal(normal.length,250);assert.equal(hard.length,250);
assert.equal(hard[0].l,1);assert.equal(hard[249].l,250);
assert(hard.every((stage,i)=>stage.l===i+1&&stage.wallCount>=2&&stage.bombCount>=2&&stage.morphSeconds>0&&stage.hasBombs));
assert(hard.every(stage=>stage.moves>=14&&stage.moves<=20&&stage.colors>=5&&stage.colors<=7));
assert(hard.every((stage,i)=>!i||stage.goal>=hard[i-1].goal));
assert(hard[0].goal>normal[0].goal&&hard[0].lockedCount>0);
assert.equal(new Set(hard.map(stage=>stage.theme)).size,10);
assert(html.includes('sc_hard_${key}')&&html.includes('`sc_${key}`'),'Hard and normal saves must be separate');
assert(html.includes('state.walls[bottom*COLS+c]')&&html.includes('wallsToBreak')&&html.includes('morphHardAnimals'),'Breakable wall gravity and timed character change must be active');
assert(shell.includes('setMode(mode)')&&html.includes('lany-mode-hard'),'Map must offer a hard mode switch');
for(let i=0;i<7;i++)assert(css.includes(`.cell.gem-${i}:not(.locked)`),'Every animal needs a distinct pastel background');
assert(css.includes('.lany-match-ring')&&css.includes('lany-soft-pop')&&css.includes('.lany-wall-break'),'Match and wall impact must remain');
console.log(JSON.stringify({pass:true,normal:normal.length,hard:hard.length,worlds:10,hardFirst:hard[0].goal,hardLast:hard[249].goal}));
