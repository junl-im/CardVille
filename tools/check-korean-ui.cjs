'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const html=fs.readFileSync('web/index.html','utf8');
const game=fs.readFileSync('web/project-overlay/project.js','utf8');
const css=fs.readFileSync('web/project-overlay/project.css','utf8');
const acc=fs.readFileSync('web/js/a11y.js','utf8');
const manifest=JSON.parse(fs.readFileSync('web/manifest.json','utf8'));
const version=JSON.parse(fs.readFileSync('web/version.json','utf8'));
assert(html.includes('<html lang="ko">'));
assert(manifest.name.includes('라니팡'));assert.equal(version.language,'ko');
for(const text of ['점수','최고 점수','단계 맵','게임 시작','드래그','목표 점수','남은 이동'])assert(html.includes(text),'Missing Korean UI '+text);
assert(game.includes('cvWorldNames=') && game.includes('cvStageNames='));
const worlds=JSON.parse(game.match(/const cvWorldNames=(\[[^;]+\]);/)[1]);
const phases=JSON.parse(game.match(/const cvStageNames=(\[[^;]+\]);/)[1]);
assert.equal(worlds.length,10);assert.equal(phases.length,25);
assert.equal(new Set(worlds.flatMap(w=>phases.map(p=>w+' · '+p))).size,250);
for(const name of worlds.concat(phases))assert(!/[a-zA-Z]/.test(name));
assert(game.includes('board.setPointerCapture') && game.includes("addEventListener('pointermove'"));
assert(game.includes('e.button!==0'),'right mouse cannot drag');
assert(game.includes("addEventListener('contextmenu'"));
assert(game.includes("addEventListener('dragstart'"));
assert(css.includes('touch-action:none'));
const fn=html.match(/function onCellClick\(r,c\)\{([\s\S]*?)\n\}/);
assert(fn && !fn[1].includes('trySwap') && !fn[1].includes('state.selected='),'Tap-to-swap must remain disabled');
assert(html.includes('function cvKeyboardSelect')&&acc.includes('cvKeyboardSelect'));
console.log(JSON.stringify({pass:true,language:'ko',worlds:worlds.length,stages:worlds.length*phases.length,dragOnlyDefault:true,rightClickMenuDisabled:true,keyboardAlternative:true},null,2));
