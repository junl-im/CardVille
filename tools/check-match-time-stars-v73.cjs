'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const source=fs.readFileSync('web/js/lany-tempo.js','utf8');
const game=fs.readFileSync('web/index.html','utf8');
const version=JSON.parse(fs.readFileSync('web/version.json','utf8'));
assert.equal(version.version,'2.3.25-beta');
assert.equal(version.matchTimeStarsV73,true);
assert(game.includes('window.LanyTempo?.awardMatchTime(matchGroups)'));
const elements=new Map();
const get=id=>{if(!elements.has(id))elements.set(id,{classList:{toggle(){}},style:{},textContent:''});return elements.get(id)};
const notices=[];
const context={window:{LanyPolish:{onTimeBonus:n=>notices.push(n)}},document:{getElementById:get,addEventListener(){},hidden:false},localStorage:{getItem:()=>null,setItem(){}},performance:{now:()=>0},setInterval:()=>1,clearInterval(){},state:{animating:false}};
vm.runInNewContext(source,context);
const tempo=context.window.LanyTempo;
assert.equal(tempo.bonusForGroups([{run:3},{run:4},{run:5},{run:6}]),9);
assert.equal(tempo.bonusForGroups([{cells:[[1,1]]}]),0);
tempo.start(1);
const initial=tempo.getRemaining();
assert.equal(tempo.awardMatchTime([{run:3}]),1);
assert.equal(tempo.awardMatchTime([{run:4}]),2);
assert.equal(tempo.awardMatchTime([{run:5}]),3);
assert.equal(tempo.getRemaining(),initial+6);
assert.deepEqual(notices,[1,2,3]);
for(let i=0;i<4;i++)tempo.awardMatchTime([{run:5}]);
assert.equal(tempo.getBonusEarned(),18);
assert.equal(tempo.awardMatchTime([{run:5}]),0);
tempo.pause();assert.equal(tempo.awardMatchTime([{run:5}]),0);
tempo.start(2);assert.equal(tempo.getBonusEarned(),0);
tempo.setEnabled(false);assert.equal(tempo.awardMatchTime([{run:5}]),0);
const match=game.match(/function finishScoreBonus\([^]*?\n\}/);
assert(match,'finish score rule missing');
const finish=vm.runInNewContext(`(${match[0]})`);
assert.equal(finish(650,93,93,18,18),455);
assert.equal(finish(650,0,93,0,18),0);
assert(875+finish(650,90,93,16,18)>=1300,'strong early clear should reach three stars');
console.log('v73 timed match rewards and three-star balance passed');
