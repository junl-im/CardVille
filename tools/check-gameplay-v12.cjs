/* v1.2 gameplay regression: authored early targets, chain rewards, responsive feel. */
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),vm=require('node:vm');
const read=p=>fs.readFileSync(p,'utf8');
const html=read('web/index.html');
const raw=html.match(/const LEVELS = \[([\s\S]*?)\];\s*let state/);
assert(raw,'250 stage list required');
const levels=vm.runInNewContext('['+raw[1]+']');
const expected=[650,850,1100,1350,1550,1750,1950,2200,2450,2700,2850,2950,3050,3200,3300,3420,3540,3660,3780,3920,4050,4180,4300,4450,4650];
assert.equal(levels.length,250);
assert.deepEqual(levels.slice(0,25).map(x=>x.goal),expected);
assert(levels.slice(0,25).every(x=>x.colors>=4&&x.colors<=5&&x.moves<=22&&x.moves>=18));
assert(levels.slice(3,25).every(x=>x.colors===5));
assert(levels[8].lockedCount>=1&&levels[9].lockedCount>=2);
const balance=require('../web/js/cardville-balance.js');
balance.apply(levels);
assert.deepEqual(levels.slice(0,25).map(x=>x.goal),expected,'Early goals must not be silently reduced');
assert.equal(levels[249].goal,3150,'Legacy later-stage cap remains backwards-compatible');
const match=html.match(/function comboPoints\(matched,chain\)\{[\s\S]*?\n\}/);
assert(match,'Capped chain points function required');
const score=vm.runInNewContext('('+match[0]+')');
assert.equal(score(3,1),90);
assert.equal(score(3,2),122);
assert.equal(score(3,3),149);
assert.equal(score(3,8),180);
assert(score(8,100)<=480,'No runaway 100-chain multiplier');
const tempo=read('web/js/lany-tempo.js');
assert(tempo.includes('function onCombo(count)')&&!tempo.includes('remaining+Math.min(3,count)'),'Combos must not regenerate time');
const shell=read('web/js/lany-shell.js'),css=read('web/css/lany-polish.css');
assert(shell.includes('mobileFullscreen()&&document.documentElement.requestFullscreen'),'Autofullscreen must be mobile only');
assert(shell.includes('if(!mobileFullscreen())return'),'Desktop fullscreen calls must be rejected');
assert(css.includes('.lany-mobile-fullscreen{display:none!important}'),'Fullscreen button must hide on desktop');
for(const name of ['lany-fall-in','lany-swap-reject','lanyDialogSpring','prefers-reduced-motion'])assert(css.includes(name),name+' missing');
const polish=read('web/js/lany-polish.js');
for(const name of ['function onFall','function invalidSwap','function onSwap','chain>=3','children.length>=8'])assert(polish.includes(name),name+' missing');
assert(html.includes('LanyPolish?.onMatch(allCells,state.combo)'),'Chain context must reach VFX');
assert(html.includes('const particleCount=particleReduced?0:'),'Reduce particles for phones and reduced motion');
assert(html.includes('bar.replaceChildren(frag)'),'HUD must reuse dots');
for(const k of ['sc_unlocked','sc_best','sc_stars','cv_last_level'])assert(html.includes(k),'Preserve existing saves');
for(const p of ['web/index.html','web/js/lany-polish.js','web/js/lany-shell.js','web/js/lany-tempo.js'])new vm.Script(p.endsWith('.html')?([...html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)].map(x=>x[1]).join('\n')):read(p),{filename:p});
console.log(JSON.stringify({pass:true,stages:250,firstGoal:levels[0].goal,tenthGoal:levels[9].goal,earlyCapProtected:true,combo8ForThree:score(3,8),mobileOnlyFullscreen:true,animations:true,saveKeysPreserved:true}));
